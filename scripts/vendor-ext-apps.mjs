// Inlines the @modelcontextprotocol/ext-apps View SDK (App class) into a TS string module,
// so ui:// resources are fully self-contained HTML (no network fetch from the sandboxed iframe).
import fs from "node:fs";
import path from "node:path";

const pkgDir = path.join(process.cwd(), "node_modules/@modelcontextprotocol/ext-apps");
const pkg = JSON.parse(fs.readFileSync(path.join(pkgDir, "package.json"), "utf8"));
let src = fs.readFileSync(path.join(pkgDir, "dist/src/app-with-deps.js"), "utf8");

const idx = src.lastIndexOf("export{");
if (idx < 0) throw new Error("export{ not found in app-with-deps.js");
const end = src.indexOf("}", idx);
const pairs = src.slice(idx + "export{".length, end).split(",").map((p) => p.trim()).filter(Boolean);
const obj = pairs.map((p) => {
  const [local, exported] = p.split(/\s+as\s+/);
  return `${JSON.stringify(exported ?? local)}:${local}`;
}).join(",");
src = src.slice(0, idx) + `globalThis.__extApps={${obj}};` + src.slice(end + 1).replace(/^;/, "");
src = src.replace(/<\/script/gi, "<\/script");

const out = `// Generated by scripts/vendor-ext-apps.mjs from @modelcontextprotocol/ext-apps@${pkg.version} (Apache-2.0). Do not edit.\n` +
  `export const EXT_APPS_VERSION = ${JSON.stringify(pkg.version)};\n` +
  `export const EXT_APPS_BUNDLE = ${JSON.stringify(src)};\n`;
fs.mkdirSync("lib/vendor", { recursive: true });
fs.writeFileSync("lib/vendor/ext-apps-bundle.ts", out);
console.log(`ext-apps ${pkg.version}: ${pairs.length} exports, ${(out.length / 1024).toFixed(0)} KB -> lib/vendor/ext-apps-bundle.ts`);
